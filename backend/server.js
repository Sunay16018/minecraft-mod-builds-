function parseAIResponse(responseText) {
  const files = [];
  const codeBlockRegex = /```(\w+)?(?::([\w/.\-_]+))?\n([\s\S]*?)```/g;
  let match;

  while ((match = codeBlockRegex.exec(responseText)) !== null) {
    const lang = match[1] || "java";
    const filePath = match[2];
    const content = match[3].trim();

    if (filePath) {
      files.push({
        path: filePath,
        content: content,
        language: lang
      });
    }
  }

  if (files.length === 0) {
    const cleanText = responseText
      .replace(/```[\w]*\n?/g, "")
      .replace(/```/g, "")
      .trim();
    if (cleanText) {
      files.push({
        path: "src/main/java/com/example/ExampleMod.java",
        content: cleanText,
        language: "java"
      });
    }
  }

  return files;
}

