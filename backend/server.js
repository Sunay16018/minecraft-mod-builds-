app.post("/api/generate", async (req, res) => {
  const startTime = Date.now();
  const requestId = `req_${Date.now()}_${Math.random().toString(36).substr(2, 9)}`;

  try {
    const {
      prompt,
      minecraft_version,
      modloader,
      mod_types,
      features,
      mod_name,
      mod_description
    } = req.body;

    if (!minecraft_version || !modloader) {
      return res.status(400).json({
        success: false,
        error: "Minecraft surumu ve modloader zorunlu."
      });
    }

    if (modloader !== "Fabric") {
      return res.status(400).json({
        success: false,
        error: "Su an sadece Fabric destekleniyor."
      });
    }

    const config = FABRIC_VERSIONS[minecraft_version];
    if (!config) {
      return res.status(400).json({
        success: false,
        error: `Desteklenmeyen Minecraft surumu: ${minecraft_version}`
      });
    }

    const modId = (mod_name || "aimod").toLowerCase().replace(/[^a-z0-9]/g, "");
    const branchName = `mod/${modId}_${Date.now()}`;
    const displayName = mod_name || `AI-Mod-${Date.now()}`;

    buildStatus.set(requestId, {
      status: "generating",
      branch: branchName,
      modName: displayName,
      version: minecraft_version,
      startTime,
      logs: ["🚀 Mod olusturma baslatildi..."]
    });

    // 1. AI'ya istek at
    console.log(`[${requestId}] Cerebras API'ye istek atiliyor...`);
    updateStatus(requestId, "🤖 Yapay zekaya istek gonderiliyor...");

    const systemPrompt = generateSystemPrompt({
      minecraft_version,
      modloader,
      mod_types: mod_types || [],
      features: features || [],
      mod_name: displayName,
      mod_description
    });

    const aiResponse = await axios.post(
      "https://api.cerebras.ai/v1/chat/completions",
      {
        model: "gpt-oss-120b",
        messages: [
          { role: "system", content: systemPrompt },
          { role: "user", content: prompt || "Minecraft modu olustur." }
        ],
        max_tokens: 16000,
        temperature: 0.2
      },
      {
        headers: {
          Authorization: `Bearer ${CEREBRAS_API_KEY}`,
          "Content-Type": "application/json"
        },
        timeout: 120000
      }
    );

    const aiContent = aiResponse.data.choices[0].message.content;
    console.log(`[${requestId}] AI yaniti alindi, parse ediliyor...`);
    updateStatus(requestId, "✅ Yapay zeka cevap verdi! Dosyalar ayristiriliyor...");

    // 2. AI yanitini parse et
    let files = parseAIResponse(aiContent);

    if (files.length === 0) {
      return res.status(500).json({
        success: false,
        error: "AI'dan gecerli kod dosyasi alinamadi."
      });
    }

    console.log(`[${requestId}] ${files.length} dosya bulundu.`);
    updateStatus(requestId, `📁 ${files.length} adet dosya olusturuldu.`);

    // 3. Zorunlu dosyalari ekle
    const existingPaths = files.map(f => f.path);

    if (!existingPaths.includes("gradle.properties")) {
      files.push({
        path: "gradle.properties",
        content: getGradleProperties(minecraft_version),
        language: "properties"
      });
    }

    if (!existingPaths.includes("build.gradle")) {
      files.push({
        path: "build.gradle",
        content: getBuildGradle(minecraft_version, modId, displayName),
        language: "gradle"
      });
    }

    if (!existingPaths.includes("settings.gradle")) {
      files.push({
        path: "settings.gradle",
        content: getSettingsGradle(),
        language: "gradle"
      });
    }

    if (!existingPaths.some(p => p.includes("fabric.mod.json"))) {
      files.push({
        path: "src/main/resources/fabric.mod.json",
        content: getFabricModJson(minecraft_version, modId, displayName, mod_description),
        language: "json"
      });
    }

    if (!existingPaths.includes("gradlew")) {
      files.push({
        path: "gradlew",
        content: getGradleWrapperScript(),
        language: "bash"
      });
    }
    if (!existingPaths.includes("gradlew.bat")) {
      files.push({
        path: "gradlew.bat",
        content: getGradleWrapperBat(),
        language: "batch"
      });
    }
    if (!existingPaths.includes("gradle/wrapper/gradle-wrapper.properties")) {
      files.push({
        path: "gradle/wrapper/gradle-wrapper.properties",
        content: getGradleWrapperProperties(config.gradle_version),
        language: "properties"
      });
    }

    // 4. GitHub'a pushla
    console.log(`[${requestId}] GitHub'a pushlaniyor...`);
    updateStatus(requestId, "☁️ Dosyalar GitHub'a pushlaniyor...");

    const gh = new GitHubHelper(GITHUB_TOKEN, GITHUB_REPO);
    await gh.createBranch(branchName);
    console.log(`[${requestId}] Branch olusturuldu: ${branchName}`);

    const workflowContent = generateWorkflow(minecraft_version, branchName);
    files.push({
      path: ".github/workflows/build-mod.yml",
      content: workflowContent,
      language: "yaml"
    });

    const commitMessage = `[Fabric] ${displayName} - MC ${minecraft_version}`;
    await gh.pushFiles(files, branchName, commitMessage);
    console.log(`[${requestId}] ${files.length} dosya pushlandi.`);
    updateStatus(requestId, `✅ GitHub'a pushlandi! Commit: ${commitMessage}`);

    // 5. Hemen cevap don (asenkron)
    updateStatus(requestId, "🔨 GitHub Actions derlemeye basladi...");
    updateStatus(requestId, "⏳ Derleniyor... (2-5 dk surebilir)");

    pollWorkflowStatus(requestId, branchName, gh);

    return res.json({
      success: true,
      requestId,
      branch: branchName,
      modName: displayName,
      minecraft_version,
      modloader,
      fileCount: files.length,
      message: "Mod kodlari GitHub'a gonderildi! Derleme basladi.",
      status: "building",
      checkStatusUrl: `/api/status/${requestId}`
    });

  } catch (error) {
    console.error(`[${requestId}] HATA:`, error.message);
    updateStatus(requestId, `❌ HATA: ${error.message}`);

    return res.status(500).json({
      success: false,
      error: error.message,
      requestId
    });
  }
});

app.get("/api/status/:requestId", async (req, res) => {
  const { requestId } = req.params;
  const status = buildStatus.get(requestId);

  if (!status) {
    return res.status(404).json({
      success: false,
      error: "Boyle bir istek bulunamadi."
    });
  }

  if (status.status === "building" || status.status === "generating") {
    try {
      const gh = new GitHubHelper(GITHUB_TOKEN, GITHUB_REPO);
      const run = await gh.getWorkflowRun(status.branch);

      if (run) {
        status.workflowRunId = run.id;
        status.workflowStatus = run.status;
        status.workflowConclusion = run.conclusion;
        status.workflowUrl = run.html_url;

        if (run.status === "completed") {
          if (run.conclusion === "success") {
            status.status = "success";
            status.message = "✅ DERLEME BASARILI!";

            const artifacts = await gh.getArtifacts(run.id);
            if (artifacts.length > 0) {
              status.artifactId = artifacts[0].id;
              status.artifactName = artifacts[0].name;
              status.downloadUrl = gh.getArtifactDownloadUrl(artifacts[0].id);
            }
          } else {
            status.status = "failed";
            status.message = `❌ DERLEME BASARISIZ: ${run.conclusion}`;
          }
        } else {
          status.message = `⏳ Derleniyor... (${run.status})`;
        }
      }
    } catch (error) {
      console.error("Status sorgulama hatasi:", error.message);
    }
  }

  return res.json({
    success: true,
    status: status.status,
    modName: status.modName,
    version: status.version,
    branch: status.branch,
    logs: status.logs,
    downloadUrl: status.downloadUrl || null,
    workflowUrl: status.workflowUrl || null,
    message: status.message || ""
  });
});

app.get("/api/download/:requestId", async (req, res) => {
  const { requestId } = req.params;
  const status = buildStatus.get(requestId);

  if (!status || !status.downloadUrl) {
    return res.status(404).json({
      success: false,
      error: "Indirme linki henuz hazir degil."
    });
  }

  return res.json({
    success: true,
    downloadUrl: status.downloadUrl,
    artifactName: status.artifactName,
    modName: status.modName,
    version: status.version
  });
});

